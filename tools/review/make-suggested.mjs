/* Writes src/concepts-suggested.js from the review rows (tools/review/rows.json, the reviewed copy of
   the Ezy keyword review sheet). Only rows with Keep = Yes go in.
   Usage: node tools/review/make-suggested.mjs */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const rows = JSON.parse(readFileSync(join(root, 'tools', 'review', 'rows.json'), 'utf8'));
const by = {};
for (const r of rows) if (r.keep === 'Yes') (by[r.cid] ||= []).push(r.word);
const lines = Object.entries(by).map(([id, ws]) => ` '${id}':[${[...new Set(ws)].sort().map(w => JSON.stringify(w).replace(/"/g, "'").replace(/^'(.*'.*)'$/, '"$1"')).join(',')}]`);
const n = Object.values(by).reduce((s, a) => s + a.length, 0);
writeFileSync(join(root, 'src', 'concepts-suggested.js'), `/* ============================================================
   SUGGESTED KEYWORDS
   Everyday words suggested by a language model (Claude) and reviewed by hand,
   November 2026: ${n} words across ${Object.keys(by).length} concepts.
   Like \`syn\` in concepts.js, they are mapped by meaning only: no study links
   these words to colors, type or shapes. The app labels them as suggested.
   Generated by tools/review/make-suggested.mjs. Edit by hand freely: a word
   here that is also in concepts.js keeps its concepts.js label.
   ============================================================ */
const SUGGESTED = {
${lines.join(',\n')}
};
`);
console.log(`Wrote src/concepts-suggested.js: ${n} words, ${Object.keys(by).length} concepts.`);
